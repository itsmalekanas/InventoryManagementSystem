// Isolated optional-cost/return integration checks. Node 22+, Chrome, built app.
const fs = require('node:fs'), path = require('node:path'), os = require('node:os'), net = require('node:net');
const { spawn } = require('node:child_process');
const assert = require('node:assert/strict');
const exe = path.resolve(process.argv[2] || process.env.INVENTORY_TEST_EXE || path.join(__dirname, '../dist/Inventory Management System.exe'));
const artifacts = fs.mkdtempSync(path.join(os.tmpdir(), 'inventory-finance-'));
const children = [];
let socket;
const pause = ms => new Promise(r => setTimeout(r, ms));
async function until(fn) { const end = Date.now() + 30000; while (Date.now() < end) { const result = await fn(); if (result) return result; await pause(80); } throw new Error('Timed out'); }
(async () => {
  const listener = net.createServer();
  await new Promise(r => listener.listen(0, '127.0.0.1', r));
  const port = listener.address().port;
  await new Promise(r => listener.close(r));
  const url = `http://127.0.0.1:${port}`;
  const app = spawn(exe, ['-port', String(port), '-data', path.join(artifacts, 'data'), '-no-tray', '-no-browser'], { windowsHide: true, stdio: 'ignore' });
  children.push(app);
  const data = async () => (await fetch(url + '/api/data')).json();
  await until(async () => { try { return (await data()).db; } catch { return false; } });
  const chrome = spawn(process.env.CHROME_PATH || 'C:/Program Files/Google/Chrome/Application/chrome.exe', ['--headless=new', '--disable-gpu', '--no-first-run', '--remote-debugging-port=0', `--user-data-dir=${path.join(artifacts, 'browser')}`, 'about:blank'], { windowsHide: true, stdio: ['ignore', 'ignore', 'pipe'] });
  children.push(chrome);
  let output = '';
  chrome.stderr.on('data', chunk => output += chunk);
  const endpoint = await until(() => output.match(/DevTools listening on (ws:\/\/[^\s]+)/)?.[1]);
  socket = new WebSocket(endpoint);
  await new Promise((r, j) => { socket.onopen = r; socket.onerror = j; });
  let id = 0;
  const pending = new Map();
  socket.onmessage = ({ data }) => { const msg = JSON.parse(data); if (pending.has(msg.id)) { const { resolve, reject } = pending.get(msg.id); pending.delete(msg.id); msg.error ? reject(new Error(JSON.stringify(msg.error))) : resolve(msg.result); } };
  const command = (method, params = {}, sessionId) => new Promise((resolve, reject) => { const seq = ++id; pending.set(seq, { resolve, reject }); socket.send(JSON.stringify({ id: seq, method, params, sessionId })); });
  const { targetId } = await command('Target.createTarget', { url: 'about:blank' });
  const { sessionId } = await command('Target.attachToTarget', { targetId, flatten: true });
  const c = (method, params) => command(method, params, sessionId);
  const evaluate = async expression => { const result = await c('Runtime.evaluate', { expression, awaitPromise: true, returnByValue: true }); if (result.exceptionDetails) throw new Error(JSON.stringify(result.exceptionDetails)); return result.result.value; };
  await c('Page.enable'); await c('Runtime.enable');
  await c('Emulation.setDeviceMetricsOverride', { width: 1440, height: 1100, deviceScaleFactor: 1, mobile: false });
  const go = async (hash, selector) => { await c('Page.navigate', { url: url + '/' + hash }); await evaluate('new Promise(resolve => requestAnimationFrame(() => requestAnimationFrame(resolve)))'); await until(() => evaluate(`!!document.querySelector(${JSON.stringify(selector)})`)); await evaluate('languageStylesReady'); };
  const click = selector => evaluate(`document.querySelector(${JSON.stringify(selector)}).click()`);
  const input = (selector, value) => evaluate(`(() => { const el = document.querySelector(${JSON.stringify(selector)}); el.value = ${JSON.stringify(value)}; el.dispatchEvent(new Event('input', { bubbles: true })); })()`);
  const holdSaves = endpoint => evaluate(`window.auditFetch = window.fetch; window.auditSaveCalls = 0; window.fetch = async (...args) => { if (String(args[0]).endsWith(${JSON.stringify(endpoint)}) && args[1]?.method === 'POST') { window.auditSaveCalls++; await new Promise(resolve => window.releaseAuditSave = resolve); } return window.auditFetch(...args); };`);
  await go('#/', '#exit-btn');
  assert.equal(await evaluate('/\\{\\w+\\}/.test(document.querySelector(".tiles").textContent)'), false);
  await go('#/reports', '.page');
  assert.equal(await evaluate('!!document.querySelector("#profit-report")'), false);
  await go('#/products', '#p-add'); await click('#p-add');
  assert.equal(await evaluate('!!document.querySelector("#pf-cost")'), false);
  assert.equal(await evaluate('document.querySelector("#modal .btn-close").getAttribute("aria-label") === t("close")'), true);
  await input('#pf [name=name]', 'Legacy cost'); await input('#pf [name=price]', '100'); await input('#pf [name=stock]', '10');
  await holdSaves('/api/products');
  await click('#pf-save'); await until(() => evaluate('window.auditSaveCalls === 1'));
  assert.equal(await evaluate('document.querySelector("#pf-save").disabled'), true);
  await click('#pf-save'); assert.equal(await evaluate('window.auditSaveCalls'), 1);
  await evaluate('window.releaseAuditSave(); window.fetch = window.auditFetch');
  await until(async () => (await data()).db.products.length === 1);
  await go('#/settings', '#sf-profit'); await click('#sf-profit');
  await click('#sf-topbar-custom');
  await input('#picker-topbarColor .color-picker-hex', '#12');
  await click('[data-color-picker=topbarColor] .color-picker-trigger');
  await click('#sf-save');
  assert.equal(await evaluate('document.querySelector("#picker-topbarColor").hidden'), false);
  assert.equal(await evaluate('document.activeElement.classList.contains("color-picker-hex")'), true);
  await input('#picker-topbarColor .color-picker-hex', '#a6e3e1');
  await click('#sf-save');
  await until(async () => (await data()).db.settings.trackProfit);
  assert.equal((await data()).db.settings.topbarColor, '#a6e3e1');
  await go('#/products', '#p-add'); await click('#p-add');
  await input('#pf [name=name]', 'Tracked item'); await input('#pf [name=price]', '100'); await input('#pf [name=stock]', '10'); await input('#pf-cost', '٦٠');
  await holdSaves('/api/images');
  await evaluate(`(() => { const files = new DataTransfer(); files.items.add(new File(['<svg xmlns="http://www.w3.org/2000/svg" width="8" height="8"><rect width="8" height="8" fill="#a6e3e1"/></svg>'], 'test.svg', { type: 'image/svg+xml' })); const input = document.querySelector('#pf-files'); input.files = files.files; input.dispatchEvent(new Event('change', { bubbles: true })); })()`);
  await until(() => evaluate('window.auditSaveCalls === 1'));
  assert.equal(await evaluate('document.querySelector("#pf-save").disabled'), true);
  await click('#pf-save'); assert.equal((await data()).db.products.length, 1);
  await evaluate('window.releaseAuditSave(); window.fetch = window.auditFetch');
  await until(() => evaluate('!document.querySelector("#pf-save").disabled'));
  await click('#pf-save');
  await until(async () => (await data()).db.products.length === 2);
  assert.equal((await data()).db.products[1].costPrice, 60);
  assert.equal((await data()).db.products[1].images.length, 1);
  await go('#/pos', '#sale-btn');
  const layout = await evaluate(`(() => { const cart = document.querySelector('.pos-cart').getBoundingClientRect(); const home = document.querySelector('.home-button').getBoundingClientRect(); return { cart: cart.width, home: home.width, height: home.height }; })()`);
  assert.ok(layout.cart > 500); assert.ok(layout.home >= 48 && layout.height >= 48);
  await evaluate(`(() => { const product = state.db.products[1]; state.cart = [{ productId: product.id, qty: 2, customPrice: 90 }]; state.cust = { name: 'Buyer', phone: '', address: '' }; renderPos(); })()`);
  await click('#sale-btn'); await until(() => evaluate('!!document.querySelector("#inv-return")'));
  const invoiceId = (await data()).db.invoices[0].id;
  assert.equal((await data()).db.invoices[0].items[0].costPrice, 60);
  assert.equal(await evaluate('document.querySelector(".invoice").textContent.includes(t("costPrice"))'), false);
  await click('#inv-return'); await input('#return-0', '١');
  // Lose the response after the server has committed the return.
  await evaluate(`window.originalFetch = window.fetch; window.loseReturn = true; window.fetch = async (...args) => { const result = await window.originalFetch(...args); if (window.loseReturn && String(args[0]).endsWith('/returns')) { window.loseReturn = false; throw new TypeError('Lost response'); } return result; };`);
  await click('#return-save');
  await until(() => evaluate('!document.querySelector("#return-pending").hidden'));
  assert.equal((await data()).db.products[1].stock, 9);
  await c('Page.reload');
  await until(() => evaluate('!!document.querySelector("#inv-return")'));
  await go('#/invoice/' + invoiceId, '#inv-return'); await click('#inv-return');
  assert.equal(await evaluate('document.querySelector("#return-fields").disabled'), true);
  await click('#return-save');
  await until(() => evaluate('!document.querySelector("#modal").classList.contains("show")'));
  const saved = (await data()).db;
  assert.equal(saved.invoices[0].returns.length, 1); assert.equal(saved.invoices[0].returns[0].total, 90); assert.equal(saved.products[1].stock, 9);
  assert.equal(await evaluate('document.querySelector("#inv-del").disabled'), true);
  await go('#/reports', '#profit-report');
  assert.equal(await evaluate('InventoryFinance.summary(state.db.invoices).profit'), 30);
  assert.equal(await evaluate('InventoryFinance.summary(state.db.invoices).net'), 90);
  await go('#/', '#theme-btn'); await click('#theme-btn');
  await until(() => evaluate('document.documentElement.dataset.bsTheme === "dark"'));
  assert.equal(await evaluate('getComputedStyle(document.body).backgroundColor'), 'rgb(43, 47, 54)');
  for (const language of ['en', 'ar']) {
    await evaluate(`(async () => { await api('PUT', '/api/settings', { ...state.db.settings, language: ${JSON.stringify(language)} }); applyLang(); route(); })()`);
    assert.equal(await evaluate('lang()'), language);
    for (const width of [1440, 960, 390]) {
      await c('Emulation.setDeviceMetricsOverride', { width, height: 1100, deviceScaleFactor: 1, mobile: false });
      await go('#/pos', '#sale-btn');
      assert.equal(await evaluate('document.querySelector(".topbar h1").textContent'), language === 'ar' ? 'بيع جديد' : 'New sale');
      assert.equal(await evaluate('document.documentElement.scrollWidth <= innerWidth'), true, `${language} ${width} overflow`);
      assert.ok(await evaluate('document.querySelector(".home-button").getBoundingClientRect().height >= 48'));
      await until(() => evaluate('!document.querySelector(".modal-backdrop")'));
      await evaluate('document.querySelector("#toasts").replaceChildren()');
      fs.writeFileSync(path.join(artifacts, `pos-${language}-${width}.png`), Buffer.from((await c('Page.captureScreenshot', { format: 'png' })).data, 'base64'));
    }
  }
  await go('#/customers', '#c-add'); await click('#c-add'); await input('#cf [name=name]', 'Audit customer');
  await holdSaves('/api/customers');
  await click('#cf-save'); await until(() => evaluate('window.auditSaveCalls === 1'));
  assert.equal(await evaluate('document.querySelector("#cf-save").disabled'), true);
  await click('#cf-save'); assert.equal(await evaluate('window.auditSaveCalls'), 1);
  await evaluate('window.releaseAuditSave(); window.fetch = window.auditFetch');
  await until(async () => (await data()).db.customers.some(customer => customer.name === 'Audit customer'));
  await go('#/settings', '#sf-profit'); await click('#sf-profit'); await click('#sf-save');
  await until(async () => !(await data()).db.settings.trackProfit);
  await go('#/reports', '.page'); assert.equal(await evaluate('!!document.querySelector("#profit-report")'), false);
  assert.equal((await data()).db.products[1].costPrice, 60);
  await go('#/', '#exit-btn'); await click('#exit-btn');
  await click('#modal [data-r="0"]');
  await until(() => evaluate('getComputedStyle(document.querySelector("#modal")).display === "none"'));
  assert.equal((await data()).db.products[1].stock, 9);
  await click('#exit-btn'); await click('#modal [data-r="1"]');
  await until(() => evaluate('document.querySelector("main[role=status] h1")?.textContent === t("appClosed")'));
  await until(() => app.exitCode !== null);
  assert.equal(app.exitCode, 0);
  const onDisk = JSON.parse(fs.readFileSync(path.join(artifacts, 'data/db.json'), 'utf8'));
  assert.equal(onDisk.invoices[0].returns.length, 1);
  console.log('Finance/return browser checks passed. Artifacts: ' + artifacts);
})().catch(error => { console.error(error); console.error('Artifacts: ' + artifacts); process.exitCode = 1; }).finally(() => { socket?.close(); for (const child of children.reverse()) child.kill(); });
